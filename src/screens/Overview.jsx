import { useEffect, useState } from "react";
import { date, loadAll } from "../data.js";
import BarProfile from "../components/BarProfile.jsx";
import StageLadder from "../components/StageLadder.jsx";
import ParamsTable from "../components/ParamsTable.jsx";
import Sources from "../components/Sources.jsx";

const LIMITS = [
  ["Входные данные синтетические", "Партии грузов, состав флота и глубины заданы сценариями. Фактических журналов рейсов 2026 года нет."],
  ["Считается речной участок", "Маршрут модели — Нижнеянск → Усть-Куйга, два участка. Морской участок и бар Яны не моделируются."],
  ["Глубины сценарные", "Модель планирует при известном сценарии глубин и не прогнозирует фактическую обстановку. Данные гидропоста и глубина судового хода — разные величины."],
  ["Нет вероятностей", "114 сценариев — вариации заданных условий, а не случайные повторения. Вероятность выполнения плана и доверительные интервалы не считаются."],
  ["Нет очереди у бара, стоимости и зимника", "Эти величины модель не рассчитывает, поэтому на дашборде их нет."],
  ["Социально значимые грузы не защищены", "Минимальные нормативы по продовольствию в оптимизацию не включены; его доставка в части сценариев хуже, чем у FCFS."],
  ["Аудит — внутренний", "Отсутствие нарушений означает, что расписание прошло проверку ограничений модели, а не подтверждает безопасность реального плавания."],
];

export default function Overview() {
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);
  useEffect(() => { loadAll().then(setData).catch((e) => setError(e.message)); }, []);
  if (error) return <p className="error">{error}</p>;
  if (!data) return <p className="muted">Загружаем данные…</p>;

  const { stages, parameters, sources, later } = data;
  const asOf = date(stages[0].as_of);

  return (
    <>
      <section className="first hero">
        <div className="problem">
          <h2>Северный завоз и Яна</h2>
          <p>
            Северный завоз — доставка топлива, угля и продовольствия в районы, куда грузы можно привезти только в
            короткую навигацию. В бассейне Яны они идут с Лены морем Лаптевых, через бар в устье, в Нижнеянск и
            дальше вверх по реке в Усть-Куйгу и Батагай.
          </p>
          <p>
            Ограничений два: малые глубины и короткое окно, июль — конец сентября. На баре гарантированная глубина
            2,2 м до 1 сентября и 3,0 м после, а гружёные суда сидят до 2,9 м. Выше по реке всё решает то, как
            распределить немногие суда между партиями грузов, чтобы успеть к срокам. Эту часть и считает наша
            модель: участок Нижнеянск → Усть-Куйга.
          </p>
        </div>
        <BarProfile />
      </section>

      <section>
        <h2>Опубликованная статистика: завоз по Яне на {asOf}</h2>
        <p className="lead">Администрация Ленского бассейна, навигация 2026 года, тонн. Доля — от плана.</p>
        <StageLadder stages={stages} />
        <p className="muted small">
          Разрыв — разница опубликованных значений. Почему груз выпал на этапе, источник не раскрывает.
        </p>
        {later.map((r) => (
          <aside className="callout quiet" key={r.report_id}>
            <h3>Более позднее сообщение, {date(r.date)}: {r.delivered_text} при плане {r.plan_text}</h3>
            <p>
              {r.publisher} приводит выполнение {r.stated_share}, но по названным числам получается {r.computed_share}.{" "}
              {r.warning} <a href={r.url} target="_blank" rel="noreferrer">Публикация</a>
            </p>
          </aside>
        ))}
        <aside className="callout">
          <h3>С результатами модели эти цифры напрямую не сравниваются</h3>
          <p>
            Официальные показатели — агрегат по всем грузам, судам и грузоотправителям за навигацию. Модель считает
            отдельный маршрут с синтетическим спросом и флотом, поэтому её тоннаж относится к другому объёму
            перевозок. Срез на {asOf} — опорный набор официальных данных проекта.
          </p>
        </aside>
      </section>

      <section>
        <h2>Ограничения модели</h2>
        <dl className="limits">
          {LIMITS.map(([k, v]) => (
            <div key={k}><dt>{k}</dt><dd>{v}</dd></div>
          ))}
        </dl>
      </section>
      <section>
        <h2>Что реальное, а что синтетическое</h2>
        <ParamsTable parameters={parameters} sources={sources} />
      </section>

      <section>
        <h2>Источники данных</h2>
        <Sources sources={sources} />
      </section>

    </>
  );
}
